// Program For Increment Decrement Operators

#include <stdio.h>

int main(void) {

	// Variable Declaration
	int a = 5;
	int b = 10;

	// Code
	printf("\n\n");
	printf("a   = %d\n", a);
	printf("a++ = %d\n", a++);
	printf("a   = %d\n", a);
	printf("++a = %d\n\n", ++a);

	printf("b   = %d\n", b);
	printf("b-- = %d\n", b--);
	printf("b   = %d\n", b);
	printf("--b = %d\n", --b);
	printf("\n\n");

	return 0;
}
