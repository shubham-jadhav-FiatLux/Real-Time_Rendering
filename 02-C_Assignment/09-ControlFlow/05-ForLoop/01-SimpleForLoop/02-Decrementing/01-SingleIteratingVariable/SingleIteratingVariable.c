// Program For 'for' Loop using Single Iterating Variable  (Decreasing)

#include <stdio.h>

int main(void) {

	// Variable Declaration
	int shubh_i;

	// Code
	printf("\n\n");

	printf("Printing Digits From 10 To 1 : \n\n");

	for (shubh_i = 10; shubh_i >= 1; shubh_i--) {
	
		printf("\t%d\n", shubh_i);
	}

	printf("\n\n");

	return 0;
}
