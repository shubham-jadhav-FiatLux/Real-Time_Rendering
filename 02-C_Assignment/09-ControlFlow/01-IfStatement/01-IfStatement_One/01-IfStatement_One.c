// Program For If Statement

#include <stdio.h>

int main(void) {

	// Variable Declaration
	int a, b, p;

	// Code
	a = 9;
	b = 30;
	p = 30;

	printf("\n\n");

	if (a < b) {
	
		printf("a Is Less Than b !!\n\n");
	}

	if (b != p) {
	
		printf("b Is NOT Equal To p !!\n\n");
	}

	printf("Both Comparisons have Been Done !!\n\n");

	return 0;
}
